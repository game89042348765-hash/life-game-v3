// 4. ЖИВЫЕ СИТУАТИВНЫЕ СЦЕНЫ И РАЗВИЛКИ «ДА / НЕТ» (Детерминированная реакция на реальное состояние)
function evaluateCompanionSignals(state) {
  if (!state || !state.companion || state.companion.enabled === false) return [];
  const signals = [];
  const comp = state.companion;
  const dismissed = (comp.dismissedOnDate && comp.dismissedOnDate[state.lastDay]) || [];

  // Сцена 1: Мобилизация длится >= 5 дней подряд (Спутник утирает лоб и спрашивает как напарник!)
  if (state.specialMode === 'red') {
    const redDays = Number(comp.redDaysCount) || 1;
    const extUntil = comp.redExtendedUntil || '';
    if (redDays >= 5 && (!extUntil || state.lastDay > extUntil) && !dismissed.includes('sig_red_fatigue')) {
      signals.push({
        id: 'sig_red_fatigue',
        fork: true,
        title: `Пять дней тянем Мобилизацию (${redDays}-й день)`,
        text: 'Я рядом, но марафон плотный — переведём дух в спокойном ходе или закатаем рукава ещё на пару дней?',
        choice1: { label: '1. Нет, жмём дальше! 🔥', act: 'companion-fork-red-push', cls: 'danger' },
        choice2: { label: '2. Да, выдыхаем 🌿', act: 'companion-fork-red-rest', cls: 'primary' },
        actionLabel: 'Выдыхаем в обычный ход',
        route: 'day',
        pulse: '[data-act="set-day-tempo"]'
      });
    }

    // Сцена 2: В Мобилизации сегодня 0 из 3 огоньков базы (Сон · Вода · Выдох)
    const careDone = (state.redCare?.sleep ? 1 : 0) + (state.redCare?.water ? 1 : 0) + (state.redCare?.rest ? 1 : 0);
    const curHour = new Date().getHours();
    if (careDone === 0 && (curHour >= 18 || redDays >= 2) && !dismissed.includes('sig_red_dry_care')) {
      signals.push({
        id: 'sig_red_dry_care',
        fork: true,
        title: 'Рывок мощный, но 0 из 3 огоньков базы отмечено',
        text: 'Чтобы фокус не сжёг ресурс, зажжём опору прямо сейчас (вода и короткий выдох)?',
        choice1: { label: '💧 Отметить Воду и Выдох', act: 'companion-fork-light-care', cls: 'primary' },
        choice2: { label: 'Позже вечером', act: 'dismiss-helper-signal', id: 'sig_red_dry_care', cls: 'ghost' },
        actionLabel: 'Открыть опоры базы',
        route: 'settings',
        pulse: '[data-act="toggle-red-care"]'
      });
    }
  }

  // Сцена 3: Возвращение после паузы >= 3 дней (Тёплая встреча без тени вины!)
  if ((Number(comp.lastReturnGap) || 0) >= 3 && !dismissed.includes('sig_welcome_back')) {
    signals.push({
      id: 'sig_welcome_back',
      fork: true,
      title: `Рад тебя видеть после перерыва (${comp.lastReturnGap} дн.)!`,
      text: 'Никаких штрафов — весь опыт сохранён. Входим сегодня плавно налегке или сразу в полный строй?',
      choice1: { label: 'Сразу в полный строй!', act: 'companion-fork-return-full', cls: 'primary' },
      choice2: { label: 'Плавно налегке 🌱', act: 'companion-fork-return-lite', cls: 'ghost' },
      actionLabel: 'Открыть сегодняшний день',
      route: 'day',
      pulse: '[data-act="set-day-tempo"]'
    });
  }

  // Сцена 4: Долгая Творческая пауза >= 5 дней
  if (state.specialMode === 'pause') {
    const pDays = Number(comp.pauseDaysCount) || 1;
    const quietUntil = comp.pauseQuietUntil || '';
    if (pDays >= 5 && (!quietUntil || state.lastDay > quietUntil) && !dismissed.includes('sig_long_pause')) {
      signals.push({
        id: 'sig_long_pause',
        fork: true,
        title: `Хорошо перевели дух (${pDays} дн. в паузе)`,
        text: 'Побудем ещё в тишине или сделаем сегодня один маленький шаг на 2 минуты?',
        choice1: { label: 'Давай шаг на 2 минуты ▶', act: 'companion-fork-pause-2min', cls: 'primary' },
        choice2: { label: 'Ещё отдыхаем 🌙', act: 'companion-fork-pause-stay', cls: 'ghost' },
        actionLabel: 'Открыть 2 минуты',
        route: 'widgets',
        pulse: '[data-act="timer-start"]'
      });
    }
  }

  // Сцена 5: Перегруз сегодняшнего списка (>= 7 незакрытых дел в Конструкторе дня)
  const dayPlan = assembleDayPlan(state, state.lastDay);
  const openTodayCount = dayPlan.visible.filter(x => !x.prog.done).length;
  if (openTodayCount >= 7 && !dismissed.includes('sig_overload_day')) {
    signals.push({
      id: 'sig_overload_day',
      fork: true,
      title: `В сегодняшнем плане ${openTodayCount} открытых дел`,
      text: 'Список сегодня плотный — оставим на виду только ключевые дела (остальные уберу до завтра) или ты в ударе?',
      choice1: { label: 'Нет, я в ресурсе! 🔥', act: 'companion-fork-overload-keep', cls: 'ghost' },
      choice2: { label: 'Да, разгрузи день 🌿', act: 'companion-fork-overload-slim', cls: 'primary' },
      actionLabel: 'Перейти в День',
      route: 'day',
      pulse: '[data-act="set-day-tempo"], [data-change="pick-main-day-item"]'
    });
  }

  // Сцена 6: В открытом этапе >= 3 разовых шагов подряд без режима «По одному шагу»
  for (const b of state.blocks) {
    if (b.archivedAt) continue;
    const curStg = state.stages.find(s => s.id === b.currentStageId && !s.archivedAt);
    if (!curStg || curStg.feedMode === 'one') continue;
    const onceQueueCount = state.items.filter(it =>
      !it.archivedAt && it.stageId === curStg.id && it.kind === 'task' &&
      (!it.schedule || it.schedule.type === 'once') && !(it.schedule && it.schedule.date) &&
      !isOneOffEverDoneInCurrentCycle(state, it)
    ).length;
    if (onceQueueCount >= 3 && !dismissed.includes('sig_conveyor_' + curStg.id)) {
      signals.push({
        id: 'sig_conveyor_' + curStg.id,
        fork: true,
        title: `В этапе «${curStg.name}» уже ${onceQueueCount} шага подряд`,
        text: 'Включить подачу «По одному шагу», чтобы в Сегодня выходил только шаг №1 без длинной простыни?',
        choice1: { label: 'Да, по одному шагу ✓', act: 'companion-fork-enable-one', stageId: curStg.id, cls: 'primary' },
        choice2: { label: 'Оставить все', act: 'dismiss-helper-signal', id: 'sig_conveyor_' + curStg.id, cls: 'ghost' },
        actionLabel: 'Открыть этап и показать',
        route: 'block',
        blockId: b.id,
        stageId: curStg.id,
        pulse: '[data-act="set-stage-feed"]'
      });
      break;
    }
  }

  // Сцена 7: Накопилось монет на выбранную «Мою награду»
  const w = calcWallet(state);
  const targetBonus = state.bonuses.find(b => !b.archivedAt && b.id === state.rewardTargetId);
  if (targetBonus && w.coins >= targetBonus.cost && !dismissed.includes('sig_reward_ready')) {
    signals.push({
      id: 'sig_reward_ready',
      fork: true,
      title: `Доступна твоя награда «${targetBonus.title}» ✦`,
      text: `На счету ${w.coins} ● (нужно ${targetBonus.cost} ●). Порадуем себя заслуженной наградой или копим дальше?`,
      choice1: { label: 'Забрать в Магазине 🎁', act: 'helper-follow-signal', cls: 'primary' },
      choice2: { label: 'Копим дальше', act: 'dismiss-helper-signal', id: 'sig_reward_ready', cls: 'ghost' },
      actionLabel: 'Открыть Магазин бонусов',
      route: 'bonuses',
      pulse: `[data-act="buy-bonus-instance"][data-id="${targetBonus.id}"]`
    });
  }

  // Сцена 8: Скопился хвост «Со вчера» (>= 2 пунктов)
  if (state.carryovers.length >= 2 && !dismissed.includes('sig_carryover')) {
    signals.push({
      id: 'sig_carryover',
      fork: true,
      title: `Ждут разбора дела «Со вчера» (${state.carryovers.length})`,
      text: 'Убрать вчерашние хвосты спокойно в «Позже», чтобы расчистить сегодняшнее утро?',
      choice1: { label: 'Да, убрать в «Позже»', act: 'companion-fork-clear-carryovers', cls: 'primary' },
      choice2: { label: 'Разберу вручную', act: 'helper-follow-signal', cls: 'ghost' },
      actionLabel: 'Разобрать спокойно',
      route: 'day',
      pulse: '[data-act="resolve-carryover"]'
    });
  }

  return signals;
}

